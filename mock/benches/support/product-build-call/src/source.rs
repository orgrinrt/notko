//! The fixture's source for a point: what a consumer's registry of `n` columns asks of the product.

use std::fmt::Write as _;

/// The columns system `k` of a registry of `n` reads and writes: four reads a quarter of the registry apart from
/// column `k`, and two writes half the registry apart from column `k + n / 8`. Spread, so no system's set sits at
/// one end of the list. `n` is a multiple of eight, and `k` is below `n / 8`.
pub fn columns_of_system(k: usize, n: usize) -> ([usize; 4], [usize; 2]) {
    let reads = [k, k + n / 4, k + n / 2, k + 3 * n / 4];
    let writes = [k + n / 8, k + n / 8 + n / 2];
    (reads, writes)
}

fn list(names: &[String]) -> String {
    let mut s = String::new();
    for name in names {
        write!(s, "Cons<{name}, ").unwrap();
    }
    s.push_str("Empty");
    s.push_str(&">".repeat(names.len()));
    s
}

fn column(i: usize) -> String {
    format!("C{i}")
}

/// The source the fixture includes for a registry of `n` columns, `n` a multiple of eight.
///
/// - A marker per column, carrying a `u32`, and the registry as one list of them.
/// - The row product through `Val`, and a value of it.
/// - One system for every eight columns, each with its read set and write set as lists and a bound that the
///   registry holds all of both (`ContainsAll`), and a `Has` pick of each read from a row.
/// - The registry's whole row written into an `Arr<4>` product and read back (`Rows`).
pub fn source(n: usize) -> String {
    assert!(
        n >= 8 && n % 8 == 0,
        "a registry of {n} columns: the bench takes a multiple of eight"
    );
    let names: Vec<String> = (0 .. n).map(column).collect();
    let mut g = String::new();
    writeln!(
        g,
        "// generated by product-build-call for a registry of {n} columns"
    )
    .unwrap();
    for name in &names {
        writeln!(
            g,
            "pub struct {name};\nimpl Elem for {name} {{ type Value = u32; }}"
        )
        .unwrap();
    }
    writeln!(g, "pub type Registry = {};", list(&names)).unwrap();
    writeln!(g, "pub type Row = <Registry as Project<Val>>::Prod;").unwrap();
    write!(g, "pub fn the_row() -> Row {{ ").unwrap();
    for i in 0 .. n {
        write!(g, "PCons {{ head: {i}u32, tail: ").unwrap();
    }
    write!(g, "PNil").unwrap();
    writeln!(g, "{} }}", " }".repeat(n)).unwrap();
    writeln!(
        g,
        "fn pick<M: Elem<Value = u32>, P: Place, X: Has<Val, M, P>>(r: &<X as Project<Val>>::Prod) -> u32 {{ *X::pick(r) }}"
    )
    .unwrap();
    writeln!(
        g,
        "fn runs<X: ContainsAll<R> + ContainsAll<W>, R: List, W: List>() {{}}"
    )
    .unwrap();
    let systems = n / 8;
    for k in 0 .. systems {
        let (reads, writes) = columns_of_system(k, n);
        let r: Vec<String> = reads.iter().map(|&i| column(i)).collect();
        let w: Vec<String> = writes.iter().map(|&i| column(i)).collect();
        writeln!(g, "pub fn system_{k}(r: &Row) -> u32 {{").unwrap();
        writeln!(g, "    runs::<Registry, {}, {}>();", list(&r), list(&w)).unwrap();
        write!(g, "    0u32").unwrap();
        for name in &r {
            write!(g, ".wrapping_add(pick::<{name}, _, Registry>(r))").unwrap();
        }
        writeln!(g, "\n}}").unwrap();
    }
    writeln!(g, "pub fn columns() -> Row {{").unwrap();
    writeln!(g, "    let mut c: <Registry as Project<Arr<4>>>::Prod = <Registry as Arrays<4>>::made(&the_row());").unwrap();
    writeln!(
        g,
        "    <Registry as Rows<Arr<4>>>::write_row(&mut c, 1, &the_row());"
    )
    .unwrap();
    writeln!(g, "    <Registry as Rows<Arr<4>>>::read_row(&c, 1)").unwrap();
    writeln!(g, "}}").unwrap();
    write!(g, "pub fn every_system(r: &Row) -> u32 {{ 0u32").unwrap();
    for k in 0 .. systems {
        write!(g, " ^ system_{k}(r)").unwrap();
    }
    writeln!(g, " }}").unwrap();
    g
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Every system of every point the bench runs reads and writes six distinct columns of the registry, so the
    /// fixture asks for what it says it asks for.
    #[test]
    fn every_system_touches_six_distinct_columns_inside_the_registry() {
        for n in [32, 64, 128, 256] {
            for k in 0 .. n / 8 {
                let (reads, writes) = columns_of_system(k, n);
                let mut all: Vec<usize> = reads.iter().chain(writes.iter()).copied().collect();
                assert!(all.iter().all(|&i| i < n), "n {n}, system {k}: {all:?}");
                all.sort_unstable();
                all.dedup();
                assert_eq!(all.len(), 6, "n {n}, system {k}");
            }
        }
    }

    #[test]
    #[should_panic(expected = "multiple of eight")]
    fn a_registry_not_a_multiple_of_eight_is_refused() {
        let _ = source(100);
    }
}
